#!/usr/bin/env python3
"""Kolmogorov measurement-operator matrix -> tab_operator_body.tex.

Reads the operator runs by their PROTOCOL STAMP, never by filename. A run
corrupted by an operator is stamped <PROTOCOL_2D>_op_<tag>; the clean row
is <PROTOCOL_2D> (protocol). Filenames are a hint (the same glob matches override and
operator runs alike) and have already caused two silent mix-ups this campaign,
so the stamp inside the payload is the only thing trusted here.

K MATTERS. DMF-Gen has clean evaluations at K = 8/16/32/64 and every operator
run is K=8, so taking "the clean DMF-Gen file" without filtering silently
compares K=64 against K=8 and understates the operator penalty. Deterministic
rows are K=1 throughout. The loader therefore pins K to 8 for generative rows
and 1 for deterministic ones, and refuses to emit a row whose clean and
corrupted entries disagree on K.

Usage: python make_operator_table.py [--tex out.tex] [--json out.json]
"""
from paths import REPO_ROOT
import argparse
import glob
import json
import math
from pathlib import Path

ROOT = REPO_ROOT
STM = ROOT / "outputs/runs" / "kolmogorov2d"
DENSITY = 655                       # the canonical 1% row
OPS = ["clean", "noise0.1", "noise0.3", "occl0.25"]
OP_HEAD = {"clean": "clean", "noise0.1": r"$\sigma{=}0.1$",
           "noise0.3": r"$\sigma{=}0.3$", "occl0.25": r"25\% slab"}
DET = {"senseiver", "mlprbf", "geofno"}     # K=1 rows
DIVERGE = 10.0                      # S3GM members stay within 4x the true max or blow up (79x to 2e7x)
ROWS = [("sit", "SiT-point"), ("s3gm", "S3GM"), ("geofno", "FNO"), ("latentfm", "Latent FM"),
        ("senseiver", "Senseiver"), ("dmfgencq", r"\dmfgen{}"),
        ("mlprbf", "MLP-RBF")]
from eval.fleet_select import REPORTED_FAMILY
from protocol import PROTOCOL_2D


def n_diverged(snapshots):
    """Frames with a member whose max |value| exceeds DIVERGE x the truth's or is not
    finite (records that store member_max_abs; other rows count none)."""
    bad = lambda r: any(not math.isfinite(v) or v > DIVERGE * r["truth_max_abs"] for v in r["member_max_abs"])
    return sum(bad(r) for r in snapshots if "member_max_abs" in r)


def load():
    """{model: {op: (rel_l2, crps, n_diverged)}} from the reported family of each model: clean
    rows stamped PROTOCOL_2D, operator rows PROTOCOL_2D_op_<tag>; TEST split, no
    clamp, canonical density and K, 50 records. More than one file per cell is an
    error, not a tie to break by sort order."""
    out = {}
    for m, _ in ROWS:
        fam = REPORTED_FAMILY[m]
        if isinstance(fam, dict):
            fam = fam["kolmogorov2d"]
        want_K = 1 if m in DET else 8
        for p in glob.glob(str(STM / fam / "*" / "Evaluation" / "kolm_fleet*.json")):
            try:
                d = json.load(open(p))
            except Exception:
                continue
            pr = d.get("protocol", "")
            if pr == PROTOCOL_2D:
                op = "clean"
            elif pr.startswith(f"{PROTOCOL_2D}_op_"):
                op = pr.split("_op_", 1)[1]
            else:
                continue
            n = d.get("n_obs")
            if not (isinstance(n, list) and n and int(n[0]) == DENSITY and len(n) == 1):
                continue
            if d.get("split") != "test" or d.get("clamp_hard") is not False:
                continue
            if int(d.get("K", -1)) != want_K or len(d.get("snapshots") or []) != 50:
                continue
            a = d["summary"]["aggregate"]
            cell = (a["rel_l2_mean"], a["crps"], n_diverged(d["snapshots"]))
            prev = out.setdefault(m, {}).get(op)
            if prev is not None and prev != cell:
                raise SystemExit(f"[operator_table] {m}/{op}: more than one canonical file ({Path(p).name})")
            out[m][op] = cell
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tex", default=str(ROOT / "outputs/paper/tab_operator_body.tex"))
    ap.add_argument("--json", default=None)
    a = ap.parse_args()
    tab = load()

    print(f"{'method':<14}" + "".join(f"{OPS[i]:>10}" for i in range(len(OPS)))
          + f"{'occl/clean':>12}")
    lines = ["% GENERATED by src/figs_pof/make_operator_table.py -- do not hand-edit"]
    missing = []
    for m, label in ROWS:
        r = tab.get(m, {})
        if "clean" not in r:
            missing.append(m)
            continue
        cells = []
        for op in OPS:
            if op not in r:
                cells.append("---")
            elif r[op][2]:
                cells.append(f"div.\\ ({r[op][2]}/50)")
            else:
                cells.append(f"{r[op][0]:.3f}")
            if op not in r:
                missing.append(f"{m}/{op}")
        ratio = (f"{r['occl0.25'][0] / r['clean'][0]:.2f}"
                 if "occl0.25" in r else "---")
        lines.append(f"{label} & " + " & ".join(cells) + f" & {ratio} \\\\")
        print(f"{m:<14}" + "".join(f"{c:>10}" for c in cells) + f"{ratio:>12}")
    Path(a.tex).write_text("\n".join(lines) + "\n")
    print(f"\nwrote {a.tex}")
    if missing:
        print("INCOMPLETE -- still missing: " + ", ".join(missing))
        print("(re-run this script when those jobs land; the table is a "
              "one-command refresh)")
    if a.json:
        Path(a.json).write_text(json.dumps(tab, indent=1))


if __name__ == "__main__":
    main()
